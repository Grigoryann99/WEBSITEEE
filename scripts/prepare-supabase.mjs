import { readFile, writeFile } from 'node:fs/promises';

// One transaction for a fresh project; existing installations use migrations instead.
const files = ['0001_concierge.sql', '0002_custom_requests.sql', '0003_revoke_table_management.sql', '0004_destination_context.sql'];
const statements = [];
for (const name of files) {
    const source = (await readFile(new URL(`../supabase/migrations/${name}`, import.meta.url), 'utf8')).trim();
    if (!/^begin;[\s\S]*commit;$/i.test(source)) throw new Error(`Unexpected transaction format: ${name}`);
    statements.push(`-- ${name}\n${source.replace(/^begin;\s*/i, '').replace(/\s*commit;$/i, '')}`);
}
const sql = `-- VeloraTravel: INITIAL SETUP FOR A NEW SUPABASE PROJECT ONLY.
-- Creates eight private tables and two functions. Does not delete existing data.
-- Run once in SQL Editor as postgres. Do not also apply migrations 0001/0002/0003.
-- Generated by: node scripts/prepare-supabase.mjs
begin;
do $$
begin
  if exists (
    select 1 from pg_tables where schemaname='public' and tablename in
      ('profiles','trips','trip_items','saved_places','concierge_threads',
       'concierge_messages','concierge_usage','custom_plan_requests')
  ) then
    raise exception 'Setup stopped: application tables already exist. Review migrations instead.';
  end if;
end $$;
grant usage on schema public to authenticated;

${statements.join('\n\n')}
commit;
`;
await writeFile(new URL('../supabase/setup-new-project.sql', import.meta.url), sql);
console.log('Prepared supabase/setup-new-project.sql (not executed against any database).');
